/** Server-only shared USD meter. No credentials, provider calls, policy mutation or operational writes. */
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- shared with Next and Deno
// @ts-ignore -- Deno requires explicit .ts imports; Next excludes Edge sources.
import type { BudgetReservation, OpenAIModel } from './tenbot-openai.ts';

export type HostedMeterRpc = (name: string, args: Record<string, unknown>) => Promise<{ data: unknown; error?: unknown }>;
export type HostedMeterOptions = { owner: string; model: OpenAIModel; requestId: string; rpc: HostedMeterRpc; timeoutMs?: number };
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const MAX_MICRO_USD = 1_000_000_000_000;
export class HostedMeteringError extends Error {
  constructor(readonly code: 'invalid-meter-configuration' | 'invalid-meter-amount' | 'meter-unavailable' | 'meter-accounting-overrun') { super(code); this.name = 'HostedMeteringError'; }
}
const object = (value: unknown): value is Record<string, unknown> => !!value && typeof value === 'object' && !Array.isArray(value);

/** Decimal ceiling, including scientific notation; never round a positive fraction of a micro-dollar down. */
export function usdToMicrousd(usd: number): number {
  if (typeof usd !== 'number' || !Number.isFinite(usd) || usd < 0 || usd > MAX_MICRO_USD / 1_000_000) throw new HostedMeteringError('invalid-meter-amount');
  const [mantissa, exponentText = '0'] = usd.toString().toLowerCase().split('e');
  const [whole, fraction = ''] = mantissa.split('.');
  const digits = BigInt(whole + fraction); const scale = fraction.length - Number(exponentText) - 6;
  const ten = BigInt(10), one = BigInt(1);
  const value = scale <= 0 ? digits * ten ** BigInt(-scale) : (digits + ten ** BigInt(scale) - one) / ten ** BigInt(scale);
  if (value > BigInt(MAX_MICRO_USD)) throw new HostedMeteringError('invalid-meter-amount');
  return Number(value);
}

/** One factory per authenticated employee turn. IDs are generated by the server, never taken from model output. */
export function createHostedOpenAIMetering(options: HostedMeterOptions): { reserveBudget(usd: number): Promise<BudgetReservation> } {
  if (!UUID.test(options.owner) || !UUID.test(options.requestId) || !['gpt-6.1-terra', 'gpt-6.1-sol'].includes(options.model) || typeof options.rpc !== 'function'
    || options.timeoutMs !== undefined && (!Number.isSafeInteger(options.timeoutMs) || options.timeoutMs < 1 || options.timeoutMs > 10000)) throw new HostedMeteringError('invalid-meter-configuration');
  const { owner, requestId, model, rpc } = options; const timeoutMs = options.timeoutMs ?? 5000;
  async function call(name: string, args: Record<string, unknown>): Promise<Record<string, unknown>> {
    let timer: ReturnType<typeof setTimeout> | undefined;
    try {
      const result = await Promise.race([
        rpc(name, args),
        new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new HostedMeteringError('meter-unavailable')), timeoutMs); }),
      ]);
      if (result.error || !object(result.data) || result.data.ok !== true) throw new HostedMeteringError('meter-unavailable');
      return result.data;
    } catch { throw new HostedMeteringError('meter-unavailable'); }
    finally { if (timer !== undefined) clearTimeout(timer); }
  }
  return { async reserveBudget(usd) {
    const reserved = usdToMicrousd(usd);
    if (reserved < 1) throw new HostedMeteringError('invalid-meter-amount');
    const id = crypto.randomUUID();
    // No automatic retry: an uncertain reserve response may already have committed.
    // Reusing its ID is rejected by SQL, so it cannot authorize a second paid dispatch.
    const result = await call('tenbot_openai_reserve', { p_user: owner, p_request_id: requestId, p_id: id, p_model: model, p_reserved_microusd: reserved });
    if (result.id !== id || result.requestId !== requestId || result.reservedMicrousd !== reserved) throw new HostedMeteringError('meter-unavailable');
    return { async settle(actualUsd) {
      // Undefined means unknown, never zero. The durable full reservation remains charged.
      const actual = actualUsd === undefined ? null : usdToMicrousd(actualUsd);
      const settled = await call('tenbot_openai_settle', { p_user: owner, p_id: id, p_actual_microusd: actual });
      if (settled.id !== id || !['measured', 'uncertain'].includes(String(settled.state)) || !Number.isSafeInteger(settled.accountedMicrousd)
        || Number(settled.accountedMicrousd) < 0 || Number(settled.accountedMicrousd) > MAX_MICRO_USD || typeof settled.overrun !== 'boolean'
        || (actual !== null && (settled.state !== 'measured' || settled.accountedMicrousd !== actual))
        || (actual === null && settled.state === 'uncertain' && settled.accountedMicrousd !== reserved)) throw new HostedMeteringError('meter-unavailable');
      if (settled.overrun === true) throw new HostedMeteringError('meter-accounting-overrun');
    } };
  } };
}
